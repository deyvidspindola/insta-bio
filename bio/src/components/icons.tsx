export function BioIcon({
  name,
  className,
}: {
  name?: IconName
  className?: string
}) {
  if (!name) return null

  const Brand = brandIcons[name]
  if (Brand) return <Brand className={className} />

  const Icon = lucideIcons[name as keyof typeof lucideIcons]
  if (!Icon) return null

  return <Icon className={className} aria-hidden="true" />
}

